// qs-compat: the native half of the compat/bin shims (wl-copy, wl-paste,
// loginctl). Not meant to be called directly.
//
//   qs-compat clip-copy [--sensitive] [--type <mime>]   stdin -> clipboard
//   qs-compat clip-clear
//   qs-compat clip-paste [--type <mime>]                clipboard -> stdout
//   qs-compat clip-types                                one MIME type per line
//   qs-compat clip-watch <command...>                   run command per change
//   qs-compat lock                                      lock the screen now

#import <AppKit/AppKit.h>
#include <dlfcn.h>
#include <spawn.h>
#include <sys/wait.h>
#include <unistd.h>

extern char** environ;

namespace {

// nspasteboard.org markers that password managers set; history tools skip
// these, so a sensitive wl-copy sets the first one.
NSString* const kConcealed = @"org.nspasteboard.ConcealedType";
NSString* const kTransient = @"org.nspasteboard.TransientType";
NSString* const kAutoGenerated = @"org.nspasteboard.AutoGeneratedType";

NSData* readStdin() {
    NSFileHandle* in = NSFileHandle.fileHandleWithStandardInput;
    return [in readDataToEndOfFile];
}

bool isPng(NSData* d) {
    static const unsigned char magic[] = {0x89, 'P', 'N', 'G'};
    return d.length >= 4 && memcmp(d.bytes, magic, 4) == 0;
}

NSString* utiForMime(NSString* mime) {
    if ([mime isEqualToString:@"image/png"]) return NSPasteboardTypePNG;
    if ([mime isEqualToString:@"image/tiff"]) return NSPasteboardTypeTIFF;
    if ([mime hasPrefix:@"text/html"]) return NSPasteboardTypeHTML;
    return NSPasteboardTypeString;
}

int clipCopy(int argc, char** argv) {
    bool sensitive = false;
    NSString* type = nil;
    for (int i = 0; i < argc; i++) {
        if (!strcmp(argv[i], "--sensitive")) sensitive = true;
        else if (!strcmp(argv[i], "--type") && i + 1 < argc) type = utiForMime(@(argv[++i]));
    }
    NSData* data = readStdin();
    if (!type) type = isPng(data) ? NSPasteboardTypePNG : NSPasteboardTypeString;

    NSPasteboard* pb = NSPasteboard.generalPasteboard;
    [pb clearContents];
    [pb setData:data forType:type];
    if (sensitive) [pb setData:[NSData data] forType:kConcealed];
    return 0;
}

int clipClear() {
    [NSPasteboard.generalPasteboard clearContents];
    return 0;
}

// Image data as PNG, converting TIFF (screenshots, most apps) if needed.
NSData* pngFrom(NSPasteboard* pb) {
    if (NSData* png = [pb dataForType:NSPasteboardTypePNG]) return png;
    NSData* tiff = [pb dataForType:NSPasteboardTypeTIFF];
    if (!tiff) return nil;
    NSBitmapImageRep* rep = [NSBitmapImageRep imageRepWithData:tiff];
    return [rep representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
}

int clipPaste(int argc, char** argv) {
    NSString* mime = nil;
    for (int i = 0; i < argc; i++)
        if (!strcmp(argv[i], "--type") && i + 1 < argc) mime = @(argv[++i]);

    NSPasteboard* pb = NSPasteboard.generalPasteboard;
    NSData* out = nil;
    if ([mime hasPrefix:@"image/"]) out = pngFrom(pb);
    else if (NSString* s = [pb stringForType:NSPasteboardTypeString]) out = [s dataUsingEncoding:NSUTF8StringEncoding];
    else if (!mime) out = pngFrom(pb);
    if (!out) return 1;
    [NSFileHandle.fileHandleWithStandardOutput writeData:out];
    return 0;
}

int clipTypes() {
    NSPasteboard* pb = NSPasteboard.generalPasteboard;
    if ([pb stringForType:NSPasteboardTypeString]) puts("text/plain;charset=utf-8");
    if ([pb dataForType:NSPasteboardTypePNG] || [pb dataForType:NSPasteboardTypeTIFF]) puts("image/png");
    return 0;
}

// Runs argv with `data` on its stdin and waits for it.
void runWith(char** argv, NSData* data) {
    int fds[2];
    if (pipe(fds) != 0) return;
    posix_spawn_file_actions_t fa;
    posix_spawn_file_actions_init(&fa);
    posix_spawn_file_actions_adddup2(&fa, fds[0], STDIN_FILENO);
    posix_spawn_file_actions_addclose(&fa, fds[1]);
    pid_t pid;
    const int rc = posix_spawnp(&pid, argv[0], &fa, nullptr, argv, environ);
    posix_spawn_file_actions_destroy(&fa);
    close(fds[0]);
    if (rc == 0) {
        const char* p = static_cast<const char*>(data.bytes);
        for (size_t left = data.length; left > 0;) {
            const ssize_t n = write(fds[1], p, left);
            if (n <= 0) break;
            p += n;
            left -= n;
        }
    }
    close(fds[1]);
    if (rc == 0) waitpid(pid, nullptr, 0);
    else fprintf(stderr, "qs-compat: cannot run %s\n", argv[0]);
}

// wl-paste --watch: macOS posts no clipboard notifications, so poll the
// change counter (a cheap integer read) four times a second.
int clipWatch(int argc, char** argv) {
    if (argc < 1) {
        fputs("qs-compat clip-watch: missing command\n", stderr);
        return 2;
    }
    signal(SIGPIPE, SIG_IGN);
    NSPasteboard* pb = NSPasteboard.generalPasteboard;
    NSInteger last = pb.changeCount;
    for (;;) {
        usleep(250000);
        @autoreleasepool {
            const NSInteger now = pb.changeCount;
            if (now == last) continue;
            last = now;
            NSArray* types = pb.types;
            if ([types containsObject:kConcealed] || [types containsObject:kTransient] ||
                [types containsObject:kAutoGenerated])
                continue;
            NSData* data = nil;
            if (NSString* s = [pb stringForType:NSPasteboardTypeString]) data = [s dataUsingEncoding:NSUTF8StringEncoding];
            else data = pngFrom(pb);
            if (data.length == 0) continue;
            setenv("CLIPBOARD_STATE", "data", 1);
            runWith(argv, data);
        }
    }
}

// SACLockScreenImmediate locks without the screensaver delay; it's what the
// Control Center "Lock Screen" item calls. Fall back to sleeping the display,
// which locks when "require password immediately" is on.
int lock() {
    if (void* h = dlopen("/System/Library/PrivateFrameworks/login.framework/Versions/Current/login", RTLD_LAZY)) {
        if (auto fn = reinterpret_cast<int (*)()>(dlsym(h, "SACLockScreenImmediate"))) return fn() == 0 ? 0 : 1;
    }
    return system("/usr/bin/pmset displaysleepnow") == 0 ? 0 : 1;
}

} // namespace

int main(int argc, char** argv) {
    @autoreleasepool {
        if (argc < 2) {
            fputs("usage: qs-compat clip-copy|clip-clear|clip-paste|clip-types|clip-watch|lock ...\n", stderr);
            return 2;
        }
        const char* cmd = argv[1];
        if (!strcmp(cmd, "clip-copy")) return clipCopy(argc - 2, argv + 2);
        if (!strcmp(cmd, "clip-clear")) return clipClear();
        if (!strcmp(cmd, "clip-paste")) return clipPaste(argc - 2, argv + 2);
        if (!strcmp(cmd, "clip-types")) return clipTypes();
        if (!strcmp(cmd, "clip-watch")) return clipWatch(argc - 2, argv + 2);
        if (!strcmp(cmd, "lock")) return lock();
        fprintf(stderr, "qs-compat: unknown command %s\n", cmd);
        return 2;
    }
}
